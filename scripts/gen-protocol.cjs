/** Deterministic pseudo-random 1-bit images in canvas orientation (row-major, 1 = black). */
function makeImage(width, height, seed, density) {
  let s = seed;
  const rnd = () => ((s = (s * 1103515245 + 12345) & 0x7fffffff) / 0x7fffffff);
  const px = new Uint8Array(width * height);
  for (let y = 0; y < height; y++) {
    for (let x = 0; x < width; x++) {
      // Blank bands and repeated rows exercise the void and repeat paths.
      if (x % 50 < 6) continue;
      if (x % 40 >= 30) {
        px[y * width + x] = y % 3 === 0 ? 1 : 0;
        continue;
      }
      px[y * width + x] = rnd() < density ? 1 : 0;
    }
  }
  // A sparse column so some rows have <= 6 black pixels (indexed packets).
  for (let y = 0; y < height; y += 9) px[y * width + 25] = 1;
  return px;
}

class ArraySource {
  constructor(width, height, px) {
    this.width = width;
    this.height = height;
    this.px = px;
  }
  getPixelColor(x, y, dir = "left") {
    let idx = y * this.width + x;
    if (dir === "left") idx = (this.height - 1 - x) * this.width + y;
    return this.px[idx] ? 0x000000 : 0xffffff;
  }
}

const images = [
  { name: "d11_label", width: 320, height: 96, direction: "left", printhead: 96, seed: 7, density: 0.3 },
  { name: "d11_short_odd", width: 77, height: 90, direction: "left", printhead: 96, seed: 3, density: 0.05 },
  { name: "top_direction", width: 384, height: 120, direction: "top", printhead: 384, seed: 11, density: 0.2 },
  { name: "m3_wide", width: 592, height: 60, direction: "top", printhead: 851, seed: 5, density: 0.2 },
  { name: "blank", width: 100, height: 96, direction: "left", printhead: 96, seed: 1, density: 0 },
].map((img) => {
  const px = img.density === 0 ? new Uint8Array(img.width * img.height) : makeImage(img.width, img.height, img.seed, img.density);
  const encoded = ImageEncoder.encode(new ArraySource(img.width, img.height, px), PageColorType.SingleColor, img.direction);
  const data = G.writeImageData(encoded, { printheadPixels: img.printhead });
  return {
    name: img.name,
    width: img.width,
    height: img.height,
    direction: img.direction,
    printhead_pixels: img.printhead,
    pixels: hex(packBits(px)),
    rows: encoded.rows,
    cols: encoded.cols,
    packets: data.map((p) => hex(p.toBytes())),
  };
});

function packBits(px) {
  const out = new Uint8Array(Math.ceil(px.length / 8));
  px.forEach((v, i) => {
    if (v) out[i >> 3] |= 0x80 >> (i & 7);
  });
  return out;
}

